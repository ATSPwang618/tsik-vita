"""Pin bounded startup checks to the TSUKIHIME overseas 960x540 asset pack (KNIF00541).

The generated Rust profile travels inside the VPK; no game bytes are embedded.
`--provisional` writes the empty key-file list used by the engine-only build; the
real profile requires the converted pack and is written by `--assets`.

Full SHA-256 verification happens here, on PC; Vita reads small metadata files and
only the first/last 4 KiB of large payloads at startup.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import zlib

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ASSETS = ROOT / 'dist/TSUKIHIME-RE/assets'
OUTPUT = ROOT / 'knife/knife-platform-vita/src/asset_profile_tsukihime_540p.rs'
MARKER = 'vita-540p-assets.json'
PROVISIONAL = (
    "// Provisional profile for the TSUKIHIME overseas 960x540 pack (KNIF00541).\n"
    "//\n"
    "// No converted TSUKIHIME asset pack exists in this engine-only build, so the\n"
    "// startup key-file check is intentionally empty: the engine reaches its own\n"
    "// archive loading and reports the missing/invalid archive instead of rejecting a\n"
    "// pack it cannot know yet. Once the pack is built, run\n"
    "//   python3 tools/generate_vita_asset_profile_tsukihime_540.py --assets <pack>/assets\n"
    "// and rebuild the VPK; that replaces this file with the real 37-file profile\n"
    "// (exact length + first/last 4 KiB CRC) and the entry becomes authoritative.\n"
    "const PROFILE: &[FileSpec] = &[];\n"
)


def generate(assets: Path):
    marker = (assets / MARKER).read_bytes()
    manifest = json.loads(marker)
    assert manifest['schema'] == 'knife-540p-assets-v1'
    assert manifest['method'] == 'native-540p-encoded-unorm-v2'
    assert manifest['color_contract'] == 'encoded-unorm8-v1'
    assert manifest['render'] == [960, 540] and manifest['display'] == [960, 540]
    assert set(manifest['codecs']) <= {1, 2, 7, 9} and 8 not in manifest['codecs'], manifest['codecs']
    assert manifest['verification']['files_hashed']
    files = {r['path']: r for r in manifest['files']}
    # Native GXM uses embedded GXP shaders; BNSH stays outside the runtime contract.
    names = sorted(n for n in files if not n.startswith(('stream/', 'shader/')))
    streams = sorted(n for n in files if n.startswith('stream/'))
    assert streams, 'pack has no stream/ entries'
    assert len(streams) <= 32_768, 'stream index exceeds the Vita resolver bound'
    names += [streams[0], streams[-1]]
    rows = []
    total_read = 0
    for name in [MARKER] + names:
        pure = PurePosixPath(name)
        assert not pure.is_absolute() and '..' not in pure.parts and ':' not in name and '\\' not in name
        p = assets / name
        size = p.stat().st_size
        if name != MARKER:
            expected = files[name]
            assert size == expected['bytes'], name
            with p.open('rb') as f:
                digest = hashlib.sha256()
                for block in iter(lambda: f.read(1024 * 1024), b''):
                    digest.update(block)
                assert digest.hexdigest() == expected['sha256'], name
        if name == MARKER or size <= 1024 * 1024:
            data = p.read_bytes()
            content = f'ContentCheck::Full(0x{zlib.crc32(data):08x})'
            total_read += size
        else:
            with p.open('rb') as f:
                first = zlib.crc32(f.read(4096))
                f.seek(size - 4096)
                last = zlib.crc32(f.read(4096))
            content = f'ContentCheck::Edges {{ first: 0x{first:08x}, last: 0x{last:08x} }}'
            total_read += 8192
        rows.append(f'    FileSpec {{ path: "{name}", bytes: {size}, content: {content} }},')
    return ('// Generated by tools/generate_vita_asset_profile_tsukihime_540.py; no game payloads.\n'
            f'// External manifest SHA-256: {hashlib.sha256(marker).hexdigest()}\n'
            f'// TSUKIHIME overseas 960x540 pack: {manifest["languages"]}, {len(rows)} key files,\n'
            f'// {total_read} bytes read once at startup, one 8192-byte buffer.\n'
            '// Large-file checks cover exact length and first/last 4096 bytes only.\n'
            'const PROFILE: &[FileSpec] = &[\n' + '\n'.join(rows) + '\n];\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--assets', type=Path, default=DEFAULT_ASSETS)
    parser.add_argument('--provisional', action='store_true',
                        help='write the provisional empty profile (engine-only build)')
    args = parser.parse_args()
    generated = PROVISIONAL if args.provisional else generate(args.assets.resolve())
    if args.check:
        assert OUTPUT.read_text(encoding='utf-8') == generated, 'Embedded TSUKIHIME asset profile is stale'
        print('TSUKIHIME asset profile matches')
    else:
        OUTPUT.write_text(generated, encoding='utf-8', newline='\n')
        print(generated.splitlines()[2] if not args.provisional else 'wrote provisional TSUKIHIME asset profile')
